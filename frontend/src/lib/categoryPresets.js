/**
 * Helper function to get presets for a specific category
 */
export const getPresetsForCategory = (categoryId) => {
  return CATEGORY_PRESETS[categoryId] || [];
};

/**
 * Helper function to get a specific preset by ID
 */
export const getPresetById = (categoryId, presetId) => {
  const presets = CATEGORY_PRESETS[categoryId] || [];
  return presets.find(p => p.id === presetId);
};

/**
 * Helper function to validate if a preset belongs to a category
 */
export const isPresetValidForCategory = (categoryId, presetId) => {
  const preset = getPresetById(categoryId, presetId);
  return preset !== undefined;
};
